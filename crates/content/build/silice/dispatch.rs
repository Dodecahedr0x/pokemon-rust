//! The Silice flavour's generated script files (SIL1 Wave 0): the registry
//! (`registry.rs`) as `dispatch.rs`, `scripts.rs`, `overrides.rs` and the report, in the shape
//! of the Emerald ones (`build/scripts.rs`). Here rather than in `build/scripts.rs` so that
//! Silice changes never move Emerald's `BUILD_ID`.

use super::registry::Registry;
use crate::codegen::ident_ok;
use crate::scripts::ScriptsOut;
use anyhow::{Context, Result, ensure};
use std::collections::BTreeSet;
use std::fmt::Write;

/// The script files of registry `s`; `unwritten` are the script names the maps use that it lacks:
/// - `dispatch.rs`: `Flow` (kept for the shape; Silice scripts return `()`), `SCRIPT_COUNT`,
///   `SCRIPT_NAMES` (sorted by name; the index is the `ScriptId`), `script_ids`, the `SCRIPTS`
///   thunk table, `script()` and `SCRIPT_DIGESTS`;
/// - `scripts.rs`: `DECOMP_NAMES` (false), one `#[path]` module per `src/silice/scripts/*.rs`
///   (`content::scripts::<module>`), and an empty trainer table (Silice trainers are Task A's);
/// - `overrides.rs`: no override (`OVERRIDES` empty);
/// - `report.txt`: the registry and the unwritten script names the maps use.
pub fn generate(s: &Registry, unwritten: &BTreeSet<String>) -> Result<ScriptsOut> {
    let n = s.scripts.len();
    let mut d = String::from(
        "// @generated by content/build.rs (build/silice/dispatch.rs)\n\
         /// How a script function finished. Silice scripts return `()`; the type keeps the\n\
         /// dispatch's shape.\n\
         #[derive(Clone, Copy, PartialEq, Eq, Debug)]\n\
         pub enum Flow {\n    Continue,\n    End,\n}\n",
    );
    writeln!(d, "pub const SCRIPT_COUNT: usize = {n};")?;
    write!(d, "pub static SCRIPT_NAMES: [&str; {n}] = [")?;
    for sc in &s.scripts {
        write!(d, "\"{}\",", sc.name)?;
    }
    d.push_str("];\n");
    d.push_str(
        "/// `ScriptId` of every script, by name.\n#[allow(non_upper_case_globals, unused_imports)]\npub mod script_ids {\n    use engine::data::ScriptId;\n",
    );
    for (i, sc) in s.scripts.iter().enumerate() {
        writeln!(d, "    pub const {}: ScriptId = ScriptId({i});", sc.name)?;
    }
    d.push_str("}\n");
    write!(
        d,
        "/// One thunk per `ScriptId`.\npub static SCRIPTS: [fn(engine::script::Ctx) -> engine::script::Script; {n}] = [\n"
    )?;
    for sc in &s.scripts {
        ensure!(ident_ok(&sc.name), "script name {:?}", sc.name);
        ensure!(ident_ok(&sc.module), "script module {:?}", sc.module);
        writeln!(
            d,
            "    |ctx| alloc::boxed::Box::pin(crate::scripts::{}::{}(ctx)),",
            sc.module, sc.name
        )?;
    }
    d.push_str("];\n");
    d.push_str(
        "/// Instantiates script `id`.\npub fn script(id: u16, ctx: engine::script::Ctx) -> engine::script::Script {\n    match SCRIPTS.get(usize::from(id)) {\n        Some(f) => f(ctx),\n        None => alloc::boxed::Box::pin(async move { ctx.log(\"unknown script id\").await }),\n    }\n}\n",
    );
    d.push_str("/// Per script: the digest of its source file (`build/silice/registry.rs`).\npub static SCRIPT_DIGESTS: &[(&str, u64)] = &[\n");
    for sc in &s.scripts {
        writeln!(d, "    (\"{}\", {:#018x}),", sc.name, sc.digest)?;
    }
    d.push_str("];\n");

    let mut rs = String::from("// @generated by content/build.rs (build/silice/dispatch.rs)\n");
    rs.push_str("/// Whether the script names come from the decomp: never in the Silice flavour.\npub const DECOMP_NAMES: bool = false;\n");
    for (m, p) in &s.modules {
        ensure!(ident_ok(m), "script module {m:?}");
        let path = p.to_str().context("script path is not UTF-8")?;
        ensure!(!path.contains('"'), "script path {path:?}");
        writeln!(
            rs,
            "#[allow(non_snake_case)]\n#[path = \"{path}\"]\npub mod {m};"
        )?;
    }
    rs.push_str(
        "/// (`ScriptId`, trainer, `TRAINER_BATTLE_*` kind) of every trainer script: none yet.\npub static TRAINER_SCRIPTS: [(u16, u16, u8); 0] = [];\n/// The trainer and `trainerbattle` kind of script `id`, if it is a trainer script.\npub fn trainer_script(id: u16) -> Option<(u16, u8)> {\n    let i = TRAINER_SCRIPTS.binary_search_by_key(&id, |r| r.0).ok()?;\n    let (_, t, k) = TRAINER_SCRIPTS[i];\n    Some((t, k))\n}\n",
    );

    let overrides = String::from(
        "// @generated by content/build.rs (build/silice/dispatch.rs)\n/// The overridden scripts: none in the Silice flavour.\npub static OVERRIDES: &[&str] = &[];\n",
    );

    let mut report = String::from("== scripts (build/silice/dispatch.rs) ==\n");
    writeln!(
        report,
        "scripts {n} in {} files; unwritten script names the maps use (dropped): {}",
        s.modules.len(),
        unwritten.len()
    )?;
    for u in unwritten {
        writeln!(report, "  unwritten: {u}")?;
    }
    Ok(ScriptsOut {
        rs,
        dispatch: d,
        overrides,
        report,
    })
}
