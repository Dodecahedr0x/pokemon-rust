//! Rust source generation (owned by Milestone 8 Task E): `consts.rs` (Gen3 constants and text
//! ids) and `data.rs` (static tables), whose bulk data (blocks, tilesets, sprite frames, the font,
//! the window and text bytes) goes into the `data.bin` blob (`blob_data.rs`). Script numbering,
//! dispatch and the script modules are in `scripts.rs` (Task D2).

use crate::blob_data::BlobOut;
use crate::build_support::TreeHash;
use crate::classify;
use crate::input::{World, warn};
use crate::scripts::scripts;
use anyhow::{Context, Result, ensure};
use extract::names::{self, Table};
use extract::schema::{BgKind, ConnectionDir, ItemPocket, from_rows};
use extract::text::{Lang, encode_lang};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

pub struct Generated {
    pub consts: String,
    pub data: String,
    /// `data.bin`, the blob `data.rs` slices.
    pub data_bin: Vec<u8>,
    /// `battle.rs` and its blob `battle.bin`.
    pub battle: String,
    pub battle_bin: Vec<u8>,
    /// The data part of `content::REPORT`: what the build degraded or approximated.
    pub report: String,
}

/// A table's entries, minus the extra numbers of a name listed at several numbers (the decomp
/// lists some specials twice, e.g. `ShowGlassWorkshopMenu` at 0x115 and 0x15C). A name keeps
/// the number `Table::value` gives it, so constants agree with the names lookups; the others
/// are reported.
fn entries(t: &'static Table) -> Vec<(u32, &'static str)> {
    t.iter()
        .filter(|&(v, n)| {
            // The lowest number listed under this (cleaned) name, as `Table::value` finds it.
            let first = t
                .iter()
                .find(|&(_, m)| clean(m) == clean(n))
                .map_or(v, |(w, _)| w);
            if first != v {
                warn(&format!(
                    "{} is listed at {first:#X} and {v:#X}: using {first:#X}",
                    clean(n)
                ));
            }
            first == v
        })
        .collect()
}

/// A names-table entry without the trailing decomp comment some carry
/// (`"SPECIAL_ShowContestPainting  @ Unused, …"`).
fn clean(name: &str) -> &str {
    name.split_whitespace().next().unwrap_or(name)
}

pub fn ident_ok(s: &str) -> bool {
    !s.is_empty()
        && !s.starts_with(|c: char| c.is_ascii_digit())
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Gen3 `MAP_*` number: `num | group << 8`.
fn map_id(id: &str) -> Result<u16> {
    let (g, n) = id.split_once('.').context("map id is not <group>.<num>")?;
    Ok(u16::from(g.parse::<u8>()?) << 8 | u16::from(n.parse::<u8>()?))
}

fn table_value(t: &Table, name: &str) -> Result<u32> {
    t.value(name)
        .with_context(|| format!("unknown {}* name {name}", t.prefix))
}

pub fn bytes_lit(b: &[u8]) -> String {
    let mut s = String::from("b\"");
    for &c in b {
        write!(s, "\\x{c:02X}").unwrap();
    }
    s.push('"');
    s
}

fn u16s_lit(v: &[u16]) -> String {
    let mut s = String::from("[");
    for x in v {
        write!(s, "{x:#X},").unwrap();
    }
    s.push(']');
    s
}

pub fn consts(w: &World, battle: &[(String, &'static str, String)]) -> Result<String> {
    let mut o = String::from("// @generated by content/build.rs\n");
    // Name -> (type, value). Aliases of one constant (`MSGBOX_NPC` in two tables) repeat with
    // the same value and are emitted once; the same name with another value is an error.
    let mut seen: BTreeMap<String, (String, String)> = BTreeMap::new();
    let mut c = |o: &mut String, name: &str, ty: &str, value: String| -> Result<()> {
        let name = clean(name);
        ensure!(ident_ok(name), "constant {name:?} is not an identifier");
        match seen.get(name) {
            Some((t, v)) => ensure!(
                t == ty && *v == value,
                "constant {name} defined twice: {t} = {v} and {ty} = {value}"
            ),
            None => {
                writeln!(o, "pub const {name}: {ty} = {value};").unwrap();
                seen.insert(name.to_string(), (ty.to_string(), value));
            }
        }
        Ok(())
    };
    // An authored game's own flags and vars take numbers of Gen3 story ones: those Gen3 names
    // would alias them, so they go.
    let taken: BTreeSet<&str> = (w.authored.iter().flat_map(|a| &a.consts))
        .map(|(_, _, v)| v.as_str())
        .collect();
    for (v, n) in entries(&names::FLAGS) {
        let value = format!("FlagId({v:#X})");
        if !taken.contains(value.as_str()) {
            c(&mut o, n, "FlagId", value)?;
        }
    }
    for (v, n) in entries(&names::VARS) {
        let value = format!("VarId({v:#X})");
        if !taken.contains(value.as_str()) {
            c(&mut o, n, "VarId", value)?;
        }
    }
    // An authored game has its own map numbers (emitted with its other ids below): Emerald's
    // `MAP_*` would alias them.
    if w.authored.is_none() {
        for m in names::MAPS {
            let v = u16::from(m.group) << 8 | u16::from(m.num);
            c(&mut o, m.constant, "MapId", format!("MapId({v:#X})"))?;
        }
    }
    for (n, ty, v) in w.authored.iter().flat_map(|s| &s.consts) {
        c(&mut o, n, ty, v.clone())?;
    }
    c(&mut o, "MAP_DYNAMIC", "MapId", "MapId(0x7F7F)".into())?;
    c(&mut o, "MAP_UNDEFINED", "MapId", "MapId(0xFFFF)".into())?;
    for (v, n) in entries(&names::SPECIALS) {
        c(&mut o, n, "u16", format!("{v:#X}"))?;
    }
    for (v, n) in entries(&names::STD_SCRIPTS)
        .into_iter()
        .chain(entries(&names::MSGBOX_TYPES))
    {
        c(&mut o, n, "u8", format!("{v:#X}"))?;
        if !n.starts_with("STD_") {
            c(&mut o, &format!("STD_{n}"), "u8", format!("{v:#X}"))?;
        }
    }
    for (v, n) in entries(&names::OBJ_EVENT_GFX) {
        c(&mut o, n, "u16", format!("{v:#X}"))?;
    }
    // `MOVEMENT_TYPE_*` as the engine's `MovementType`: the one mapping (`classify::movement`)
    // of both object templates and the lowered `setobjectmovementtype` (Task D2).
    for (_, n) in entries(&names::MOVEMENT_TYPES) {
        c(&mut o, n, "MovementType", classify::movement(n).0)?;
    }
    for (v, n) in entries(&names::ITEMS) {
        c(&mut o, n, "u16", format!("{v:#X}"))?;
    }
    // Unnamed numbers (`FLAG_0x123`) the maps use (the lowered scripts write them
    // `FlagId(0x123)`, so they need no constant).
    let mut sources: Vec<String> = Vec::new();
    for m in &w.maps {
        sources.push(extract::export::to_ron(m)?);
    }
    let hex: BTreeSet<String> = sources
        .iter()
        .flat_map(|s| classify::hex_names(s))
        .collect();
    for n in hex {
        let (ty, table): (&str, &Table) = match n.split("0x").next().unwrap() {
            "FLAG_" => ("FlagId", &names::FLAGS),
            "VAR_" => ("VarId", &names::VARS),
            "SPECIAL_" => ("u16", &names::SPECIALS),
            "ITEM_" => ("u16", &names::ITEMS),
            "OBJ_EVENT_GFX_" => ("u16", &names::OBJ_EVENT_GFX),
            "STD_" => ("u8", &names::STD_SCRIPTS),
            _ => continue,
        };
        let v = table_value(table, &n)?;
        let value = match ty {
            "FlagId" | "VarId" => format!("{ty}({v:#X})"),
            _ => format!("{v:#X}"),
        };
        c(&mut o, &n, ty, value)?;
    }
    for (n, ty, v) in battle {
        c(&mut o, n, ty, v.clone())?;
    }
    for (i, k) in w.texts.keys().enumerate() {
        c(&mut o, k, "TextId", format!("TextId({i})"))?;
    }
    // The decomp's `EventScript_ResetAllMapFlags` (`names::RESET_ALL_MAP_FLAGS`), for the
    // Emerald new game (`new_game.rs`).
    o.push_str("/// The flags Gen3 `EventScript_ResetAllMapFlags` sets (`NewGameInitData`).\npub const RESET_ALL_MAP_FLAGS: &[FlagId] = &[");
    for f in names::RESET_ALL_MAP_FLAGS {
        write!(o, "FlagId({:#X}),", table_value(&names::FLAGS, f)?)?;
    }
    o.push_str("];\n");
    Ok(o)
}

fn dir_of(d: ConnectionDir) -> Option<&'static str> {
    Some(match d {
        ConnectionDir::South => "Dir::Down",
        ConnectionDir::North => "Dir::Up",
        ConnectionDir::West => "Dir::Left",
        ConnectionDir::East => "Dir::Right",
        ConnectionDir::Dive | ConnectionDir::Emerge => return None,
    })
}

/// Where a new game starts: outside the player's house in Littleroot (in front of the warp
/// leading to `LittlerootTown_BrendansHouse_1F`), else the middle of the first map. An authored
/// game's start is its own (`AuthoredIn::start`).
fn new_game(w: &World) -> Result<(u16, i16, i16, &'static str)> {
    if let Some(s) = &w.authored {
        let (name, x, y, facing) = &s.start;
        let m = (w.maps.iter().find(|m| &m.name == name))
            .with_context(|| format!("the new game's map {name} is not loaded"))?;
        return Ok((u16::from(m.group) << 8 | u16::from(m.num), *x, *y, facing));
    }
    new_game_cell(w).map(|(m, x, y)| (m, x, y, "Dir::Down"))
}

/// Emerald's (and the stub's) start cell; they face down.
fn new_game_cell(w: &World) -> Result<(u16, i16, i16)> {
    if let Some(m) = w.maps.iter().find(|m| m.name == "LittlerootTown")
        && let Some(warp) = m
            .warps
            .iter()
            .find(|wp| wp.dest_map.as_deref() == Some("LittlerootTown_BrendansHouse_1F"))
    {
        return Ok((
            map_id(&format!("{}.{}", m.group, m.num))?,
            warp.x,
            warp.y + 1,
        ));
    }
    if w.dir.is_none() {
        let m = &w.maps[0];
        let (x, y) = crate::stub::START;
        return Ok((u16::from(m.group) << 8 | u16::from(m.num), x, y));
    }
    let m = w.maps.first().context("no maps")?;
    Ok((
        u16::from(m.group) << 8 | u16::from(m.num),
        (m.layout.width / 2) as i16,
        (m.layout.height / 2) as i16,
    ))
}

/// The player's default name: the authored game's, else Emerald's fixed SACHA.
fn player_name(w: &World) -> &str {
    w.authored
        .as_ref()
        .map_or("SACHA", |a| a.player_name.as_str())
}

fn ui_texts(lang: Lang, player_name: &str) -> Result<[(&'static str, Vec<u8>); 4]> {
    // Gen3 `gText_Yes`/`gText_No`, the default rival name (May: FLORA in French) and the
    // fixed player name.
    let (yes, no, rival) = match lang {
        Lang::Fr => ("OUI", "NON", "FLORA"),
        Lang::En => ("YES", "NO", "MAY"),
    };
    Ok([
        ("UI_YES", encode_lang(yes, lang)?),
        ("UI_NO", encode_lang(no, lang)?),
        ("UI_RIVAL_NAME", encode_lang(rival, lang)?),
        ("PLAYER_NAME", encode_lang(player_name, lang)?),
    ])
}

/// `data.rs`, its blob (`data.bin`) and the data part of the report.
pub fn data(w: &World, global_digest: u64) -> Result<(String, Vec<u8>, String)> {
    let mut blob = BlobOut::new("DATA");
    let mut report = String::new();
    let s = scripts(w);
    let script_id: BTreeMap<&str, usize> = s
        .names
        .iter()
        .enumerate()
        .map(|(i, n)| (n.as_str(), i))
        .collect();
    let sid = |name: &str| -> Result<String> {
        let i = script_id
            .get(name)
            .with_context(|| format!("script {name} has no id"))?;
        Ok(format!("ScriptId({i})"))
    };
    let opt_sid = |name: &Option<String>| -> Result<String> {
        Ok(match name {
            Some(n) => format!("Some({})", sid(n)?),
            None => "None".into(),
        })
    };

    let mut o = String::from("// @generated by content/build.rs\n");
    o.push_str("use engine::data::*;\n\n");

    // ---- tilesets ----
    let mut tileset_names = BTreeSet::new();
    writeln!(
        o,
        "static EMPTY_TS: Tileset = Tileset {{ tiles: &[], palettes: &[], metatiles: &[], attributes: &[] }};"
    )?;
    for t in &w.tilesets {
        let n = &t.file.name;
        ensure!(ident_ok(n), "tileset name {n:?}");
        tileset_names.insert(n.as_str());
        let f = &t.file;
        ensure!(
            f.metatiles.len() == f.attributes.len(),
            "tileset {n}: metatiles/attributes length"
        );
        let line = format!(
            "pub static TS_{n}: Tileset = Tileset {{ tiles: {}, palettes: {}, metatiles: {}, attributes: {} }};",
            blob.tiles(&t.tiles),
            blob.pals(&f.palettes),
            blob.metatiles(&f.metatiles),
            blob.u16s(&f.attributes)
        );
        writeln!(o, "{line}")?;
    }

    // ---- maps ----
    let mut map_arms = String::new();
    let mut map_type_arms = String::new();
    let exported: BTreeSet<u16> = w
        .maps
        .iter()
        .map(|m| u16::from(m.group) << 8 | u16::from(m.num))
        .collect();
    let mut movement_fallbacks = BTreeSet::new();
    for m in &w.maps {
        let n = &m.name;
        ensure!(ident_ok(n), "map name {n:?}");
        let l = &m.layout;
        for ts in [&l.primary, &l.secondary] {
            ensure!(
                tileset_names.contains(ts.as_str()),
                "map {n}: tileset {ts} not exported"
            );
        }
        let blocks = from_rows(&l.blocks);
        ensure!(
            blocks.len() == usize::from(l.width) * usize::from(l.height),
            "map {n}: {} blocks for {}x{}",
            blocks.len(),
            l.width,
            l.height
        );
        let border = from_rows(&l.border);
        ensure!(border.len() == 4, "map {n}: border is not 2x2");
        let blocks = blob.u16s(&blocks);

        let mut objects = String::new();
        for ob in &m.objects {
            let gfx = classify::gfx(&ob.gfx)
                .with_context(|| format!("map {n}: object {} gfx {}", ob.local_id, ob.gfx))?;
            let (movement, exact) = classify::movement(&ob.movement);
            if !exact {
                movement_fallbacks.insert(format!("{} -> {movement}", ob.movement));
            }
            let trainer = names::TRAINER_TYPES
                .value(&ob.trainer_type)
                .unwrap_or_else(|| {
                    warn(&format!(
                        "map {n}: object {}: unknown trainer type {}, using 0",
                        ob.local_id, ob.trainer_type
                    ));
                    0
                });
            let flag = match &ob.flag {
                Some(f) => format!("Some(FlagId({:#X}))", table_value(&names::FLAGS, f)?),
                None => "None".into(),
            };
            write!(
                objects,
                "ObjectEvent {{ local_id: {}, gfx: {gfx}, x: {}, y: {}, elevation: {}, movement: {movement}, range: ({}, {}), trainer_type: {trainer}, trainer_sight: {}, script: {}, hide_flag: {flag} }},",
                ob.local_id,
                ob.x,
                ob.y,
                ob.elevation,
                ob.range_x,
                ob.range_y,
                ob.trainer_sight_or_berry_tree as u8,
                opt_sid(&ob.script)?
            )?;
        }
        let mut warps = String::new();
        for wp in &m.warps {
            write!(
                warps,
                "WarpEvent {{ x: {}, y: {}, elevation: {}, dest_map: MapId({:#X}), dest_warp: {} }},",
                wp.x,
                wp.y,
                wp.elevation,
                map_id(&wp.dest_map_id)?,
                wp.dest_warp
            )?;
        }
        let mut coords = String::new();
        for c in &m.coords {
            // Weather triggers (no var) and script-less coords do nothing in this engine.
            let (Some(var), Some(script)) = (&c.var, &c.script) else {
                continue;
            };
            write!(
                coords,
                "CoordEvent {{ x: {}, y: {}, elevation: {}, var: VarId({:#X}), value: {}, script: {} }},",
                c.x,
                c.y,
                c.elevation,
                table_value(&names::VARS, var)?,
                c.value,
                sid(script)?
            )?;
        }
        let mut bgs = String::new();
        for b in &m.bgs {
            let kind = match &b.kind {
                BgKind::Script {
                    facing,
                    script: Some(script),
                } => {
                    let facing = match facing {
                        1 => "Some(Dir::Up)",
                        2 => "Some(Dir::Down)",
                        3 => "Some(Dir::Right)",
                        4 => "Some(Dir::Left)",
                        _ => "None",
                    };
                    format!(
                        "BgKind::Script {{ facing: {facing}, script: {} }}",
                        sid(script)?
                    )
                }
                BgKind::HiddenItem { item, flag } => format!(
                    "BgKind::HiddenItem {{ item: {:#X}, flag: FlagId({:#X}) }}",
                    table_value(&names::ITEMS, item)?,
                    table_value(&names::FLAGS, flag)?
                ),
                _ => continue,
            };
            write!(
                bgs,
                "BgEvent {{ x: {}, y: {}, elevation: {}, kind: {kind} }},",
                b.x, b.y, b.elevation
            )?;
        }
        let mut conns = String::new();
        for c in &m.connections {
            let Some(d) = dir_of(c.dir) else { continue };
            let id = map_id(&c.map_id)?;
            if c.map.is_none() || !exported.contains(&id) {
                continue;
            }
            write!(
                conns,
                "Connection {{ dir: {d}, offset: {}, map: MapId({id:#X}) }},",
                c.offset
            )?;
        }
        let ms = &m.scripts;
        let var_scripts = |v: &[extract::schema::VarScript]| -> Result<String> {
            let mut s = String::from("&[");
            for t in v {
                write!(
                    s,
                    "VarScript {{ var: VarId({:#X}), value: {}, script: {} }},",
                    table_value(&names::VARS, &t.var)?,
                    t.value,
                    sid(&t.script)?
                )?;
            }
            s.push(']');
            Ok(s)
        };
        writeln!(
            o,
            "pub static M_{n}: MapData = MapData {{ name: \"{n}\", width: {}, height: {}, blocks: {blocks}, border: {}, primary: &TS_{}, secondary: &TS_{}, objects: &[{objects}], warps: &[{warps}], coords: &[{coords}], bgs: &[{bgs}], connections: &[{conns}], scripts: MapScripts {{ on_load: {}, on_transition: {}, on_resume: {}, on_return_to_field: {}, on_frame: {}, on_warp_into: {} }}, allow_running: {}, map_type: {} }};",
            l.width,
            l.height,
            u16s_lit(&border),
            l.primary,
            l.secondary,
            opt_sid(&ms.on_load)?,
            opt_sid(&ms.on_transition)?,
            opt_sid(&ms.on_resume)?,
            opt_sid(&ms.on_return_to_field)?,
            var_scripts(&ms.on_frame)?,
            var_scripts(&ms.on_warp_into)?,
            m.header.allow_running,
            m.header.map_type
        )?;
        writeln!(
            map_arms,
            "        {:#X} => Some(&M_{n}),",
            u16::from(m.group) << 8 | u16::from(m.num)
        )?;
        let ty = classify::map_type(m.header.map_type, n);
        if ty != "Outdoor" {
            writeln!(
                map_type_arms,
                "        {:#X} => MapType::{ty},",
                u16::from(m.group) << 8 | u16::from(m.num)
            )?;
        }
    }
    writeln!(
        o,
        "/// What `GameData::map` returns for a map that was not exported: 0x0 cells, no events.\npub static MISSING_MAP: MapData = MapData {{ name: \"MISSING\", width: 0, height: 0, blocks: &[], border: [0; 4], primary: &EMPTY_TS, secondary: &EMPTY_TS, objects: &[], warps: &[], coords: &[], bgs: &[], connections: &[], scripts: MapScripts {{ on_load: None, on_transition: None, on_resume: None, on_return_to_field: None, on_frame: &[], on_warp_into: &[] }}, allow_running: false, map_type: 0 }};"
    )?;
    writeln!(
        o,
        "/// The exported map with Gen3 number `id` (`MAP_*`).\npub fn map(id: u16) -> Option<&'static MapData> {{\n    match id {{\n{map_arms}        _ => None,\n    }}\n}}"
    )?;
    writeln!(
        o,
        "/// The battle background's map type of map `id` (`MAP_*`; see `classify::map_type`).\npub fn map_type(id: u16) -> MapType {{\n    match id {{\n{map_type_arms}        _ => MapType::Outdoor,\n    }}\n}}"
    )?;
    writeln!(o, "pub const MAP_COUNT: usize = {};", w.maps.len())?;
    write!(o, "pub static MAP_IDS: [MapId; {}] = [", w.maps.len())?;
    for m in &w.maps {
        write!(
            o,
            "MapId({:#X}),",
            u16::from(m.group) << 8 | u16::from(m.num)
        )?;
    }
    o.push_str("];\n");
    for f in &movement_fallbacks {
        writeln!(report, "movement type approximated: {f}")?;
    }

    // ---- sprites ----
    let mut sprite_arms = String::new();
    for sp in &w.sprites {
        let n = &sp.file.name;
        ensure!(ident_ok(n), "sprite name {n:?}");
        let frames: Vec<String> = sp.frames.iter().map(|f| blob.tiles(f)).collect();
        writeln!(
            o,
            "pub static S_{n}: SpriteData = SpriteData {{ width: {}, height: {}, frames: &[{}], palette: {} }};",
            sp.file.cell_width,
            sp.file.cell_height,
            frames.join(","),
            blob.pal(&sp.file.palette)
        )?;
        writeln!(
            sprite_arms,
            "        {:#X} => Some(&S_{n}),",
            sp.file.gfx_id
        )?;
    }
    writeln!(
        o,
        "/// The sprite of Gen3 graphics id `gfx` (`OBJ_EVENT_GFX_*`).\npub fn sprite(gfx: u16) -> Option<&'static SpriteData> {{\n    match gfx {{\n{sprite_arms}        _ => None,\n    }}\n}}"
    )?;
    let player = w
        .sprites
        .iter()
        .find(|s| s.file.name == "BRENDAN_NORMAL")
        .context("no BRENDAN_NORMAL sprite")?;
    ensure!(
        player.frames.len() == 18,
        "BRENDAN_NORMAL has {} frames, expected 18 (walk + run)",
        player.frames.len()
    );
    writeln!(
        o,
        "pub static PLAYER_SPRITE: &SpriteData = &S_BRENDAN_NORMAL;"
    )?;

    // ---- font, window ----
    ensure!(
        w.glyphs.len() == w.widths.len(),
        "font glyphs/widths length"
    );
    writeln!(
        o,
        "pub static FONT: Font = Font {{ glyphs: {}, widths: {} }};",
        blob.glyphs(&w.glyphs),
        blob.bytes(&w.widths)
    )?;
    let win = &w.window;
    writeln!(
        o,
        "pub static WINDOW: WindowGfx = WindowGfx {{ tiles: {}, palette: {}, text_fg: {}, text_shadow: {}, text_bg: {} }};",
        blob.tiles(&w.window_tiles),
        blob.pal(&win.palette),
        win.text_fg,
        win.text_shadow,
        win.text_bg
    )?;

    // ---- texts ----
    write!(o, "pub static TEXTS: [&[u8]; {}] = [", w.texts.len())?;
    for b in w.texts.values() {
        ensure!(b.last() == Some(&0xFF), "text not 0xFF-terminated");
        o.push_str(&blob.bytes(b));
        o.push(',');
    }
    o.push_str("];\n");
    write!(o, "pub static TEXT_NAMES: [&str; {}] = [", w.texts.len())?;
    for k in w.texts.keys() {
        write!(o, "\"{k}\",")?;
    }
    o.push_str("];\n");
    writeln!(
        o,
        "/// `manifest.language`: the charmap of `TEXTS`.\npub const LANG: &str = \"{}\";",
        w.lang.code()
    )?;
    writeln!(
        o,
        "/// sha1 of the ROM the data was extracted from (empty for the stub).\npub const SOURCE_SHA1: &str = \"{}\";",
        w.sha1
    )?;
    for (name, b) in ui_texts(w.lang, player_name(w))? {
        writeln!(o, "pub static {name}: &[u8] = {};", bytes_lit(&b))?;
    }

    // ---- behaviors, new game ----
    o.push_str("pub static BEHAVIORS: [Behavior; 256] = [");
    for b in classify::behavior_table() {
        write!(o, "Behavior::{b},")?;
    }
    for raw in 0..=255u8 {
        let name = names::behavior_name(raw);
        let (v, exact) = classify::behavior_class(&name);
        if !exact {
            writeln!(report, "behavior approximated: {name} ({raw:#04X}) -> {v}")?;
        }
    }
    o.push_str("];\n");
    let (map, x, y, facing) = new_game(w)?;
    writeln!(
        o,
        "pub const NEW_GAME: (MapId, i16, i16, Dir) = (MapId({map:#X}), {x}, {y}, {facing});"
    )?;

    // ---- names for logs ----
    for (name, table) in [
        ("SPECIAL_NAMES", &names::SPECIALS),
        ("STD_NAMES", &names::STD_SCRIPTS),
    ] {
        let entries: Vec<_> = table.iter().collect();
        write!(o, "pub static {name}: [(u16, &str); {}] = [", entries.len())?;
        for (v, n) in entries {
            write!(o, "({v:#X}, \"{}\"),", clean(n))?;
        }
        o.push_str("];\n");
    }

    tables(w, &mut blob, &mut o)?;
    let whiteout = s.names.iter().position(|n| n == "EventScript_WhiteOut");
    writeln!(
        o,
        "/// `EventScript_WhiteOut`, when the scripts have it (decomp names, Task D2).\npub const SCRIPT_WHITEOUT: Option<ScriptId> = {};",
        whiteout.map_or("None".into(), |i| format!("Some(ScriptId({i}))"))
    )?;
    let repel = s.names.iter().position(|n| n == "EventScript_RepelWoreOff");
    writeln!(
        o,
        "/// `EventScript_RepelWoreOff`, when the scripts have it (Milestone 9).\npub const SCRIPT_REPEL_WORE_OFF: Option<ScriptId> = {};",
        repel.map_or("None".into(), |i| format!("Some(ScriptId({i}))"))
    )?;

    // ---- digests (the explorer's incremental revalidation) ----
    o.push_str("/// Per map (decomp name), in map order: the inputs of its compiled data (the map file, its\n/// tilesets, its connected maps' layouts and tilesets; `build/codegen.rs`, `map_digests`). The\n/// generator that compiles them is in [`GLOBAL_DIGEST`].\npub static MAP_DIGESTS: &[(&str, u64)] = &[");
    for (n, d) in map_digests(w)? {
        write!(o, "(\"{n}\", {d:#018x}),")?;
    }
    o.push_str("];\n");
    writeln!(
        o,
        "/// The battle tables, items and other tables, texts, the behavior table, the prelude and\n/// every non-generated content source (`build/codegen.rs`, `global_digest`).\npub const GLOBAL_DIGEST: u64 = {global_digest:#018x};"
    )?;
    // An authored game's own tables (`AuthoredIn::data_rs`).
    if let Some(a) = &w.authored {
        o.push_str(&a.data_rs);
    }
    o.push_str(&blob.static_decl("data.bin"));
    writeln!(
        report,
        "data.bin: {} B ({} B shared between identical items)",
        blob.bytes.len(),
        blob.deduped
    )?;
    Ok((o, blob.bytes, report))
}

/// Gen3-encoded bytes of a table string (decomp `.string` syntax), 0xFF-terminated.
fn table_text(w: &World, s: &str, what: &str) -> Result<Vec<u8>> {
    encode_lang(s, w.lang).with_context(|| format!("{what}: {s:?}"))
}

/// The `std_string()` id of the first field string (Task L): past every `STDSTRING_*`.
const FIELD_STRING_BASE: u8 = 0x80;

/// `ITEMS`, `multichoice()`, `std_string()`, `map_section()` (Task C's `tables/`) and `emote()`
/// (Task A's field-effect pics). Each is empty when the extract lacks its file.
fn tables(w: &World, blob: &mut BlobOut, o: &mut String) -> Result<()> {
    let t = &w.tables;
    ensure!(
        (names::STD_STRINGS.iter().count() as u32) < u32::from(FIELD_STRING_BASE),
        "STDSTRING_* reach FIELD_STRING_BASE"
    );
    writeln!(
        o,
        "/// `std_string(FIELD_STRING_BASE + i)` is `extract::tables::FIELD_STRINGS[i]` (Task L).\npub const FIELD_STRING_BASE: u8 = {FIELD_STRING_BASE:#X};"
    )?;
    let mut items = String::new();
    for (i, it) in t.items.items.iter().enumerate() {
        if let Some(v) = names::ITEMS.value(&it.id) {
            ensure!(
                v as usize == i,
                "{} is item {i}, the names table says {v}",
                it.id
            );
        }
        // `ITEM_NONE` (0) is no item, though the ROM gives it `POCKET_ITEMS`; the unused slots
        // (`ITEM_034` …) stay the "????????" items the ROM has.
        let pocket = match it.pocket {
            Some(p) if i != 0 => p,
            _ => {
                items.push_str("None,");
                continue;
            }
        };
        let pocket = match pocket {
            ItemPocket::Items => "Pocket::Items",
            ItemPocket::KeyItems => "Pocket::KeyItems",
            ItemPocket::PokeBalls => "Pocket::PokeBalls",
            ItemPocket::TmHm => "Pocket::TmHm",
            ItemPocket::Berries => "Pocket::Berries",
        };
        write!(
            items,
            "Some(ItemInfo {{ name: {}, pocket: {pocket}, price: {}, key: {} }}),",
            blob.bytes(&table_text(w, &it.name, &it.id)?),
            it.price,
            it.importance != 0
        )?;
    }
    writeln!(
        o,
        "/// `gItems` by `ITEM_*` (`None`: `ITEM_NONE`, `POCKET_NONE`).\npub static ITEMS: [Option<ItemInfo>; {}] = [{items}];",
        t.items.items.len()
    )?;

    let mut arms = String::new();
    for (name, list) in &t.multichoice.lists {
        let v = table_value(&names::MULTICHOICE, name)?;
        let choices: Vec<String> = list
            .iter()
            .map(|c| Ok(blob.bytes(&table_text(w, c, name)?)))
            .collect::<Result<_>>()?;
        writeln!(
            o,
            "static MULTI_{v}: [&[u8]; {}] = [{}]; // {name}",
            choices.len(),
            choices.join(", ")
        )?;
        writeln!(arms, "        {v} => Some(&MULTI_{v}),")?;
    }
    writeln!(
        o,
        "/// `sMultichoiceLists[list]` (`MULTI_*`).\npub fn multichoice(list: u8) -> Option<&'static [&'static [u8]]> {{\n    match list {{\n{arms}        _ => None,\n    }}\n}}"
    )?;
    for (fun, doc, table, entries) in [
        (
            "std_string",
            "`gStdStrings[id]` (`STDSTRING_*`)",
            &names::STD_STRINGS,
            &t.std_strings.strings,
        ),
        (
            "map_section",
            "The name of map section `id` (`MAPSEC_*`, `gRegionMapEntries`)",
            &names::MAP_SECTIONS,
            &t.map_sections.sections,
        ),
    ] {
        let mut arms = String::new();
        for (name, text) in entries {
            let v = table_value(table, name)?;
            writeln!(
                arms,
                "        {v} => Some({}), // {name}",
                blob.bytes(&table_text(w, text, name)?)
            )?;
        }
        // Task L: the field strings follow as content's own ids, `FIELD_STRING_BASE + i`
        // (`extract::tables::FIELD_STRINGS` order; `prelude::special` buffers them).
        if fun == "std_string" {
            for (i, name) in extract::tables::FIELD_STRINGS.iter().enumerate() {
                if let Some(text) = t.field_strings.strings.get(*name) {
                    writeln!(
                        arms,
                        "        {} => Some({}), // {name}",
                        FIELD_STRING_BASE as usize + i,
                        blob.bytes(&table_text(w, text, name)?)
                    )?;
                }
            }
        }
        writeln!(
            o,
            "/// {doc}.\npub fn {fun}(id: u8) -> Option<&'static [u8]> {{\n    match id {{\n{arms}        _ => None,\n    }}\n}}"
        )?;
    }

    let mut arms = String::new();
    for e in &w.emotes {
        let variant = match e.name.as_str() {
            "ExclamationMark" => "Exclamation",
            "QuestionMark" => "Question",
            "HeartIcon" => "Heart",
            _ => {
                warn(&format!("field effect {} is not an emote, skipped", e.name));
                continue;
            }
        };
        ensure!(
            e.width <= 64 && e.height <= 64,
            "emote {} is {}x{}",
            e.name,
            e.width,
            e.height
        );
        let frames: Vec<String> = e.frames.iter().map(|f| blob.tiles(f)).collect();
        writeln!(
            o,
            "static EMOTE_{variant}: SpriteData = SpriteData {{ width: {}, height: {}, frames: &[{}], palette: {} }};",
            e.width,
            e.height,
            frames.join(","),
            blob.pal(&e.palette)
        )?;
        writeln!(arms, "        Emote::{variant} => Some(&EMOTE_{variant}),")?;
    }
    writeln!(
        o,
        "/// The emote bubbles (Gen3 field effects).\n#[allow(unreachable_patterns)]\npub fn emote(e: Emote) -> Option<&'static SpriteData> {{\n    match e {{\n{arms}        _ => None,\n    }}\n}}"
    )?;
    Ok(())
}

/// The data a map's play depends on, by map name: the map file (layout, header, events by
/// script name), its two tilesets (metatiles, attributes, palettes, tiles) and, for each
/// connection, the connected map's layout and tilesets (its edge is drawn and walked onto).
/// Independent of the export order and of every other map.
pub fn map_digests(w: &World) -> Result<Vec<(String, u64)>> {
    let tilesets: BTreeMap<&str, &crate::input::TilesetIn> = w
        .tilesets
        .iter()
        .map(|t| (t.file.name.as_str(), t))
        .collect();
    let maps: BTreeMap<&str, &extract::schema::MapFile> =
        w.maps.iter().map(|m| (m.name.as_str(), m)).collect();
    let layout = |h: &mut TreeHash, m: &extract::schema::MapFile| -> Result<()> {
        h.file(&m.name, extract::export::to_ron(&m.layout)?.as_bytes());
        for ts in [&m.layout.primary, &m.layout.secondary] {
            let t = tilesets
                .get(ts.as_str())
                .with_context(|| format!("map {}: tileset {ts} not exported", m.name))?;
            h.file(ts, extract::export::to_ron(&t.file)?.as_bytes());
            let tiles: Vec<u8> = t
                .tiles
                .iter()
                .flatten()
                .flat_map(|r| r.to_le_bytes())
                .collect();
            h.write(&tiles);
        }
        Ok(())
    };
    let mut out = Vec::new();
    for m in &w.maps {
        let mut h = TreeHash::new();
        h.file("map", extract::export::to_ron(m)?.as_bytes());
        layout(&mut h, m)?;
        for c in &m.connections {
            if let Some(other) = c.map.as_deref().and_then(|n| maps.get(n)) {
                layout(&mut h, other)?;
            }
        }
        out.push((m.name.clone(), h.finish()));
    }
    Ok(out)
}

/// The hash of every non-generated, non-test source the content depends on, beyond the extracted
/// data: `src/` (the prelude, `lib.rs`, …; not the override files `src/overrides/<Name>.rs`,
/// each in its script's digest), the generator itself (`build/`, its
/// support tables) and `extract/src` (the text codec, schema and lowering the generator calls).
/// A change there can change any map's compiled data, so it counts as global. Test sources
/// (`*_tests.rs`, `tests/`, …; `build_support::is_test_source`) are left out.
///
/// Only the stub's and Emerald's sources ([`src_source`], [`build_source`],
/// [`extract_source`]): the Silice flavour's are [`sources_digest_for`]'s.
#[allow(dead_code)] // used by the tests
pub fn sources_digest(content_dir: &std::path::Path) -> std::io::Result<u64> {
    sources_digest_for(content_dir, None)
}

/// Whether `rel` (under `crates/content/src`) is a source of the stub and Emerald builds
/// (`silice` false) or of the Silice build (SIL1 Wave 0). The flavours share the crate root,
/// the Gen3 prelude, `blob.rs` and `samples.rs`; `silice/` is Silice's only, and `overrides/`
/// and `new_game.rs` are Emerald's only. So a Silice edit never moves the Emerald `BUILD_ID`
/// or `GLOBAL_DIGEST` (its checkpoint trees and explorer dbs), and the reverse.
pub fn src_source(silice: bool, rel: &str) -> bool {
    crate::build_support::is_build_source(rel)
        && match silice {
            true => !rel.starts_with("overrides/") && rel != "new_game.rs",
            false => !rel.starts_with("silice/"),
        }
}

/// [`src_source`] for `crates/content/build`: `build/silice/` is the Silice build's only.
pub fn build_source(silice: bool, rel: &str) -> bool {
    crate::build_support::is_build_source(rel) && (silice || !rel.starts_with("silice/"))
}

/// [`src_source`] for `crates/extract/src`: `games/` (the games dir formats) is the Silice
/// build's only.
pub fn extract_source(silice: bool, rel: &str) -> bool {
    crate::build_support::is_build_source(rel) && (silice || !rel.starts_with("games/"))
}

/// Whether `rel` (under `games/silice`) is a Silice build input: everything but the map
/// editor's edit scripts (`edits/`), the import report and the validator's exceptions.
pub fn games_source(rel: &str) -> bool {
    !rel.starts_with("edits/") && rel != "IMPORT-REPORT.md" && rel != "check-exceptions.ron"
}

/// [`sources_digest`] of a flavour: `silice_games` is the Silice games dir (`games/silice`), or
/// `None` for the stub and Emerald. The Silice digest also covers the games dir's
/// [`games_source`]s except the maps and layouts (`MAP_DIGESTS`), and leaves out the scripts
/// (`src/silice/scripts/`, `SCRIPT_DIGESTS`), as the Emerald one covers no map or IR script.
pub fn sources_digest_for(
    content_dir: &std::path::Path,
    silice_games: Option<&std::path::Path>,
) -> std::io::Result<u64> {
    use crate::build_support::Content;
    let silice = silice_games.is_some();
    let mut h = TreeHash::new();
    h.tree(
        "src/",
        &content_dir.join("src"),
        // An override's source is in its script's digest (`SCRIPT_DIGESTS`), so editing one
        // is not a global change (Task N); `overrides/mod.rs`, if any, still is.
        &|rel: &str| {
            src_source(silice, rel)
                && !rel.starts_with("silice/scripts/")
                && !(rel.starts_with("overrides/") && rel != "overrides/mod.rs")
        },
        Content::Text,
    )?;
    h.tree(
        "build/",
        &content_dir.join("build"),
        &|rel: &str| build_source(silice, rel),
        Content::Text,
    )?;
    if let Some(games) = silice_games {
        h.tree(
            "games/",
            games,
            &|rel: &str| {
                games_source(rel) && !rel.starts_with("maps/") && !rel.starts_with("layouts/")
            },
            Content::Text,
        )?;
    }
    let support = content_dir.join("build/support");
    if support.is_dir() {
        h.tree(
            "support/",
            &support,
            &|rel: &str| rel.ends_with(".ron"),
            Content::Text,
        )?;
    }
    let extract = content_dir.join("../extract/src");
    if extract.is_dir() {
        h.tree(
            "extract/",
            &extract,
            &|rel: &str| extract_source(silice, rel),
            Content::Text,
        )?;
    }
    Ok(h.finish())
}

/// `GLOBAL_DIGEST`: `sources` ([`sources_digest`]), the generated battle module and blob, the
/// texts, Task C's tables, the emotes, the object sprites, the font, the window, the UI texts,
/// the new-game start and the behavior table: everything compiled that is not one map's.
pub fn global_digest(w: &World, sources: u64, battle_rs: &str, battle_bin: &[u8]) -> Result<u64> {
    let tiles = |t: &[crate::input::Tile]| -> Vec<u8> {
        t.iter().flatten().flat_map(|r| r.to_le_bytes()).collect()
    };
    let mut h = TreeHash::new();
    h.write(&sources.to_le_bytes());
    for sp in &w.sprites {
        h.file(&sp.file.name, extract::export::to_ron(&sp.file)?.as_bytes());
        for f in &sp.frames {
            h.write(&tiles(f));
        }
    }
    h.file("font.glyphs", w.glyphs.as_flattened());
    h.file("font.widths", &w.widths);
    h.file("window", extract::export::to_ron(&w.window)?.as_bytes());
    h.file("window.tiles", &tiles(&w.window_tiles));
    for (name, b) in ui_texts(w.lang, player_name(w))? {
        h.file(name, &b);
    }
    // Emerald's new game faces down: its digest input stays as it was before the facing.
    let (map, x, y, facing) = new_game(w)?;
    let facing = if facing == "Dir::Down" {
        String::new()
    } else {
        format!(" {facing}")
    };
    h.file("new_game", format!("{map} {x} {y}{facing}").as_bytes());
    h.file("battle.rs", battle_rs.as_bytes());
    h.file("battle.bin", battle_bin);
    for (k, v) in &w.texts {
        h.file(k, v);
    }
    let t = &w.tables;
    h.file("items", extract::export::to_ron(&t.items)?.as_bytes());
    h.file(
        "multichoice",
        extract::export::to_ron(&t.multichoice)?.as_bytes(),
    );
    h.file(
        "std_strings",
        extract::export::to_ron(&t.std_strings)?.as_bytes(),
    );
    h.file(
        "map_sections",
        extract::export::to_ron(&t.map_sections)?.as_bytes(),
    );
    h.file(
        "field_strings",
        extract::export::to_ron(&t.field_strings)?.as_bytes(),
    );
    for e in &w.emotes {
        let tiles: Vec<u8> = e
            .frames
            .iter()
            .flatten()
            .flatten()
            .flat_map(|r| r.to_le_bytes())
            .collect();
        h.file(&e.name, &tiles);
    }
    h.file("behaviors", classify::behavior_table().join(",").as_bytes());
    h.file("lang", w.lang.code().as_bytes());
    Ok(h.finish())
}

/// `sources`: the hash of the non-generated content sources (`build/main.rs` computes it;
/// `global_digest`).
pub fn generate(w: &World, sources: u64) -> Result<Generated> {
    let b = crate::battle::generate(&w.battle, w).context("battle data")?;
    let global = global_digest(w, sources, &b.rs, &b.bin)?;
    let (data, data_bin, data_report) = data(w, global)?;
    Ok(Generated {
        consts: consts(w, &b.consts)?,
        data,
        data_bin,
        battle: b.rs,
        report: format!("{data_report}{}", b.report),
        battle_bin: b.bin,
    })
}
