//! Scripts (owned by Milestone 8 Task D2): `ScriptId` numbering, the dispatch (`SCRIPT_NAMES`,
//! `script_ids`, `script()`, `SCRIPT_DIGESTS`, all in `$OUT_DIR/dispatch.rs`, `include!`d into
//! `content::data`), the script modules (`$OUT_DIR/scripts.rs`) and the classification report
//! (`$OUT_DIR/report.txt`, `content::REPORT`). Wave 0: today's legacy path, moved from
//! `codegen.rs`; the support tables are read and checked, not used yet.

use crate::codegen::ident_ok;
use crate::input::{World, warn};
use anyhow::{Context, Result, bail, ensure};
use extract::codegen::Support;
use extract::schema::{BgKind, MapFile};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::Path;

/// What [`generate`] produces.
pub struct ScriptsOut {
    /// `scripts.rs`: the script modules.
    pub rs: String,
    /// `dispatch.rs`, part of `content::data`.
    pub dispatch: String,
    /// `report.txt` (`content::REPORT`).
    pub report: String,
}

/// The committed support tables (`build/support/{commands,specials,movements}.ron`).
pub fn support(build_dir: &Path) -> Result<Support> {
    let read = |name: &str| -> Result<String> {
        let path = build_dir.join("support").join(name);
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))
    };
    Support::parse(
        &read("commands.ron")?,
        Some(&read("specials.ron")?),
        Some(&read("movements.ron")?),
    )
}

/// The scripts of `w` (`dir`: the extracted dir, `None` for the stub; `out`: `$OUT_DIR`, where
/// Task D2 writes one file per module).
pub fn generate(
    dir: Option<&Path>,
    out: &Path,
    w: &World,
    support: &Support,
) -> Result<ScriptsOut> {
    let _ = (dir, out);
    ensure!(
        !support.commands.is_empty() && !support.specials.is_empty(),
        "empty support tables"
    );
    Ok(ScriptsOut {
        rs: scripts_rs(w)?,
        dispatch: dispatch(w)?,
        report: String::from(
            "legacy script generator: no classification report (Milestone 8 Task D2)\n",
        ),
    })
}

/// All script names with their `ScriptId` (position), and the module (file stem) defining
/// each one when scripts were generated.
pub struct Scripts {
    pub names: Vec<String>,
    pub module: BTreeMap<String, String>,
}

fn map_script_refs(m: &MapFile) -> Vec<&str> {
    let s = &m.scripts;
    let mut v: Vec<&str> = Vec::new();
    v.extend(m.objects.iter().filter_map(|o| o.script.as_deref()));
    v.extend(m.coords.iter().filter_map(|c| c.script.as_deref()));
    v.extend(m.bgs.iter().filter_map(|b| match &b.kind {
        BgKind::Script { script, .. } => script.as_deref(),
        _ => None,
    }));
    for o in [
        &s.on_load,
        &s.on_transition,
        &s.on_resume,
        &s.on_return_to_field,
        &s.on_dive_warp,
    ] {
        v.extend(o.as_deref());
    }
    v.extend(s.on_frame.iter().map(|t| t.script.as_str()));
    v.extend(s.on_warp_into.iter().map(|t| t.script.as_str()));
    v
}

/// `ScriptId` numbering: the keys of `scripts/legacy_index.ron` in order, then any script a map
/// refers to that the index lacks (sorted). Without an index: the map references, sorted.
pub fn scripts(w: &World) -> Scripts {
    let refs: BTreeSet<String> = w
        .maps
        .iter()
        .flat_map(map_script_refs)
        .map(str::to_string)
        .collect();
    let mut names = Vec::new();
    let mut module = BTreeMap::new();
    if let Some(index) = &w.index {
        for (name, e) in &index.scripts {
            names.push(name.clone());
            let stem = std::path::Path::new(&e.file)
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or(&e.file)
                .to_string();
            module.insert(name.clone(), stem);
        }
    }
    for r in refs {
        if !module.contains_key(&r) {
            if w.index.is_some() {
                warn(&format!(
                    "script {r} is referenced by a map but not in legacy_index.ron"
                ));
            }
            names.push(r);
        }
    }
    Scripts { names, module }
}

/// `dispatch.rs`: script count, names, ids, the `script()` match and the digests.
pub fn dispatch(w: &World) -> Result<String> {
    let s = scripts(w);
    let mut o = String::from("// @generated by content/build.rs\n");
    writeln!(o, "pub const SCRIPT_COUNT: usize = {};", s.names.len())?;
    write!(o, "pub static SCRIPT_NAMES: [&str; {}] = [", s.names.len())?;
    for n in &s.names {
        write!(o, "\"{n}\",")?;
    }
    o.push_str("];\n");
    o.push_str("/// `ScriptId` of every script, by name.\n#[allow(unused_imports)]\npub mod script_ids {\n    use engine::data::ScriptId;\n");
    for (i, n) in s.names.iter().enumerate() {
        ensure!(ident_ok(n), "script name {n:?}");
        writeln!(o, "    pub const {n}: ScriptId = ScriptId({i});")?;
    }
    o.push_str("}\n");
    o.push_str("async fn log_only(ctx: Ctx, what: &'static str) {\n    ctx.log(what).await;\n}\n");
    o.push_str("/// Instantiates script `id`.\npub fn script(id: u16, ctx: Ctx) -> Script {\n    match id {\n");
    for (i, n) in s.names.iter().enumerate() {
        match s.module.get(n) {
            Some(m) => {
                ensure!(ident_ok(m), "script module {m:?}");
                writeln!(o, "        {i} => Box::pin(crate::scripts::{m}::{n}(ctx)),")?
            }
            None => writeln!(
                o,
                "        {i} => Box::pin(log_only(ctx, \"script {n} not generated\")),"
            )?,
        }
    }
    o.push_str("        _ => Box::pin(log_only(ctx, \"unknown script id\")),\n    }\n}\n");
    o.push_str("/// Per script (decomp name): its lowered source and closure (Milestone 8 Task D2).\npub static SCRIPT_DIGESTS: &[(&str, u64)] = &[];\n");
    Ok(o)
}

pub fn scripts_rs(w: &World) -> Result<String> {
    let s = scripts(w);
    let mut o = String::from("// @generated by content/build.rs\n");
    if w.index.is_some() && w.dir.is_none() {
        bail!("scripts need an extracted dir");
    }
    for m in s.module.values().collect::<BTreeSet<_>>() {
        writeln!(
            o,
            "#[allow(non_snake_case, non_upper_case_globals, unused_mut, unused_variables, unused_assignments, unreachable_code, clippy::all)]\npub mod {m} {{\n    use crate::prelude::*;\n    include!(concat!(env!(\"PKR_EXTRACTED\"), \"/scripts/{m}.rs\"));\n}}"
        )?;
    }
    Ok(o)
}
