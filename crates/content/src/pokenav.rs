#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mr_stone_is_first_and_his_first_call_sets_the_flag() {
        let c = &CALLS[0];
        assert!(c.shown_if.is_none());
        assert!(c.name.starts_with(&[0xC7, 0xCC])); // "MR"
        assert_eq!(c.lines[0].sets, Some(FLAG_ENABLE_MR_STONE_POKENAV));
        assert_eq!(c.lines[1].requires, Some(FLAG_ENABLE_MR_STONE_POKENAV));
        assert!(CALLS.len() > 1);
    }

    #[test]
    fn the_start_menu_offers_the_pokenav_after_the_bag() {
        use engine::data::{GameData, StartAction};
        let menu = crate::Game::default().start_menu();
        let Some(i) = menu.iter().position(|e| e.action == StartAction::Pokenav) else {
            assert!(menu.is_empty(), "a start menu without POKéNAV");
            return;
        };
        assert_eq!(menu[i].shown_if, Some(crate::consts::FLAG_SYS_POKENAV_GET));
        assert_eq!(menu[i - 1].action, StartAction::Bag);
        assert_eq!(menu[i + 1].action, StartAction::PlayerCard);
    }
}
