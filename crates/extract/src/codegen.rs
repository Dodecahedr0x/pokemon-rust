struct Prog<'a> {
    rom: &'a Rom,
    insns: BTreeMap<u32, Insn>,
    unknown: BTreeMap<u32, u8>,
    labels: Vec<Label>,
    label_at: BTreeMap<u32, usize>,
    blocks: BTreeMap<u32, Block>,
    fns: BTreeSet<u32>,
    /// Function entry -> its blocks, entry first then label order.
    regions: BTreeMap<u32, Vec<u32>>,
    texts: BTreeMap<u32, String>,
    /// Movement offset -> (name, map).
    movements: BTreeMap<u32, (String, String)>,
    /// Movement offsets in naming order.
    movement_order: Vec<u32>,
    can_end: BTreeSet<u32>,
    /// Instructions reading a `cond` Gen3 would have taken from another function.
    foreign_cond: BTreeSet<u32>,
    stats: Stats,
}

/// Generates the scripts of `maps` (in export order).
pub fn generate(rom: &Rom, maps: &[MapRoots], header: &str) -> Result<Generated> {
    let mut p = Prog {
        rom,
        insns: BTreeMap::new(),
        unknown: BTreeMap::new(),
        labels: Vec::new(),
        label_at: BTreeMap::new(),
        blocks: BTreeMap::new(),
        fns: BTreeSet::new(),
        regions: BTreeMap::new(),
        texts: BTreeMap::new(),
        movements: BTreeMap::new(),
        movement_order: Vec::new(),
        can_end: BTreeSet::new(),
        foreign_cond: BTreeSet::new(),
        stats: Stats::default(),
    };
    p.discover(maps)?;
    p.build_blocks()?;
    p.build_regions()?;
    p.name_data()?;
    p.analyse();

    let mut out = Generated::default();
    for m in maps {
        out.files.insert(m.map.clone(), header.to_string());
    }
    for (&off, name) in &p.texts {
        let s = text::round_trip_at(rom, off).with_context(|| format!("text {name}"))?;
        out.texts.insert(name.clone(), s);
        out.text_offsets.insert(name.clone(), off);
    }
    let fns: Vec<u32> = p
        .labels
        .iter()
        .map(|l| l.off)
        .filter(|o| p.fns.contains(o))
        .collect();
    for f in fns {
        let l = &p.labels[p.label_at[&f]];
        let (name, map, root) = (l.name.clone(), l.map.clone(), l.root);
        let src = p.emit_fn(f)?;
        let file = out.files.get_mut(&map).context("label of an unknown map")?;
        file.push('\n');
        file.push_str(&src);
        out.index
            .scripts
            .insert(name, ScriptEntry { file: map, root });
    }
    for off in p.movement_order.clone() {
        let (name, map) = p.movements[&off].clone();
        let actions = movement::decode(rom, off).with_context(|| format!("movement {name}"))?;
        let mut unknown = Vec::new();
        let lit = movement::array_literal(&actions, "", &mut unknown);
        for u in unknown {
            *p.stats.unknown_movement_actions.entry(u).or_default() += 1;
        }
        let file = out
            .files
            .get_mut(&map)
            .context("movement of an unknown map")?;
        writeln!(
            file,
            "\npub static {name}: [Step; {}] = {lit};",
            actions.len()
        )?;
        out.index.movements.insert(name, map);
    }
    p.stats.fns = p.fns.len();
    p.stats.labels = p.labels.len();
    p.stats.texts = out.texts.len();
    p.stats.movements = out.index.movements.len();
    p.stats.unknown_ops = p.unknown.clone();
    out.stats = p.stats;
    Ok(out)
}

impl Prog<'_> {
    fn label(&mut self, off: u32, name: String, map: &str, root: bool) {
        self.label_at.insert(off, self.labels.len());
        self.labels.push(Label {
            off,
            name,
            map: map.to_string(),
            root,
        });
    }

    /// Labels every canonical root, then scans each root's code and labels jump targets.
    fn discover(&mut self, maps: &[MapRoots]) -> Result<()> {
        let canonical = roots::canonical(maps.iter().flat_map(|m| &m.roots));
        let mut order = Vec::new();
        for m in maps {
            for (name, off) in &m.roots {
                if canonical[off] == *name && !self.label_at.contains_key(off) {
                    self.label(*off, name.clone(), &m.map, true);
                    order.push((*off, name.clone(), m.map.clone()));
                }
            }
        }
        let mut visited = BTreeSet::new();
        // Final label order: each root followed by the labels its scan created.
        let mut rank: BTreeMap<u32, usize> = BTreeMap::new();
        for (root, name, map) in order {
            rank.insert(root, rank.len());
            let mut n = 0;
            let mut queue = VecDeque::from([root]);
            while let Some(start) = queue.pop_front() {
                let mut pc = start;
                while visited.insert(pc) {
                    let insn = scripts::decode(self.rom, pc).with_context(|| name.clone())?;
                    let Some(insn) = insn else {
                        self.unknown.insert(pc, self.rom.u8(pc)?);
                        break;
                    };
                    for a in &insn.args {
                        if let Operand::Script(t) = *a {
                            if !self.label_at.contains_key(&t) {
                                self.label(t, format!("{name}_L{n}"), &map, false);
                                rank.insert(t, rank.len());
                                n += 1;
                            }
                            queue.push_back(t);
                        }
                    }
                    let (len, stop) = (insn.len, insn.is_terminator());
                    self.insns.insert(pc, insn);
                    if stop {
                        break;
                    }
                    pc += len;
                }
            }
        }
        self.labels.sort_by_key(|l| rank[&l.off]);
        self.label_at = self
            .labels
            .iter()
            .enumerate()
            .map(|(i, l)| (l.off, i))
            .collect();
        let mut prev: Option<&Insn> = None;
        for i in self.insns.values() {
            if let Some(p) = prev {
                ensure!(
                    p.off + p.len <= i.off,
                    "instruction at {:#x} starts inside {} at {:#x}",
                    i.off,
                    p.name,
                    p.off
                );
            }
            prev = Some(i);
        }
        Ok(())
    }

    fn build_blocks(&mut self) -> Result<()> {
        for l in &self.labels {
            let mut insns = Vec::new();
            let mut pc = l.off;
            let end = loop {
                let Some(i) = self.insns.get(&pc) else {
                    ensure!(self.unknown.contains_key(&pc), "{pc:#x} was not decoded");
                    break End::Unknown(pc);
                };
                insns.push(pc);
                if i.is_terminator() {
                    break End::Terminated;
                }
                pc += i.len;
                if self.label_at.contains_key(&pc) {
                    break End::Fallthrough(pc);
                }
            };
            self.blocks.insert(l.off, Block { insns, end });
        }
        Ok(())
    }

    fn edges(&self, block: u32) -> Vec<(Edge, u32)> {
        let b = &self.blocks[&block];
        let mut out = Vec::new();
        for pc in &b.insns {
            let i = &self.insns[pc];
            for a in &i.args {
                if let Operand::Script(t) = *a {
                    let kind = match i.name {
                        "goto" | "goto_if" => Edge::Jump,
                        _ => Edge::Call,
                    };
                    out.push((kind, t));
                }
            }
        }
        if let End::Fallthrough(t) = b.end {
            out.push((Edge::Jump, t));
        }
        out
    }

    /// Picks the functions and the blocks each one owns.
    fn build_regions(&mut self) -> Result<()> {
        self.fns = self
            .labels
            .iter()
            .filter(|l| l.root)
            .map(|l| l.off)
            .collect();
        for &b in self.blocks.keys() {
            for (kind, t) in self.edges(b) {
                if kind == Edge::Call {
                    self.fns.insert(t);
                }
            }
        }
        loop {
            let mut owners: BTreeMap<u32, BTreeSet<u32>> = BTreeMap::new();
            self.regions.clear();
            for &f in &self.fns {
                let mut seen = BTreeSet::from([f]);
                let mut stack = vec![f];
                while let Some(b) = stack.pop() {
                    for (kind, t) in self.edges(b) {
                        if kind == Edge::Jump && !self.fns.contains(&t) && seen.insert(t) {
                            stack.push(t);
                        }
                    }
                }
                for &b in &seen {
                    owners.entry(b).or_default().insert(f);
                }
                let mut blocks: Vec<u32> = seen.into_iter().collect();
                blocks.sort_by_key(|b| (*b != f, self.label_at[b]));
                self.regions.insert(f, blocks);
            }
            let shared: Vec<u32> = owners
                .iter()
                .filter(|(b, o)| o.len() > 1 && !self.fns.contains(b))
                .map(|(b, _)| *b)
                .collect();
            if shared.is_empty() {
                for l in &self.labels {
                    ensure!(owners.contains_key(&l.off), "{} is unreachable", l.name);
                }
                return Ok(());
            }
            self.fns.extend(shared);
        }
    }

    /// Names texts and movements after the first label (in label order) whose block uses them.
    fn name_data(&mut self) -> Result<()> {
        for l in &self.labels {
            let (mut nt, mut nm) = (0, 0);
            for pc in &self.blocks[&l.off].insns {
                for a in &self.insns[pc].args {
                    match *a {
                        Operand::Text(Some(t)) if !self.texts.contains_key(&t) => {
                            self.texts.insert(t, format!("{}_T{nt}", l.name));
                            nt += 1;
                        }
                        Operand::Movement(Some(m)) if !self.movements.contains_key(&m) => {
                            self.movements
                                .insert(m, (format!("{}_M{nm}", l.name), l.map.clone()));
                            self.movement_order.push(m);
                            nm += 1;
                        }
                        Operand::Braille(Some(_)) => {
                            bail!("{}: braille text is not supported", l.name)
                        }
                        _ => {}
                    }
                }
            }
        }
        Ok(())
    }

    /// Function entries reached from `f` by a tail call, and by `call`.
    fn fn_targets(&self, f: u32) -> (Vec<u32>, Vec<u32>) {
        let (mut tail, mut calls) = (Vec::new(), Vec::new());
        for b in &self.regions[&f] {
            for (kind, t) in self.edges(*b) {
                if !self.fns.contains(&t) {
                    continue;
                }
                match kind {
                    Edge::Jump => tail.push(t),
                    Edge::Call => calls.push(t),
                }
            }
        }
        (tail, calls)
    }

    fn region_has(&self, f: u32, names: &[&str]) -> bool {
        self.regions[&f].iter().any(|b| {
            self.blocks[b]
                .insns
                .iter()
                .any(|pc| names.contains(&self.insns[pc].name))
        })
    }

    /// Fixpoint of `base`: a function has the property if it has it itself or reaches (by tail
    /// call or call) a function that has it.
    fn closure(&self, base: impl Fn(u32) -> bool) -> BTreeSet<u32> {
        let mut set: BTreeSet<u32> = self.fns.iter().copied().filter(|&f| base(f)).collect();
        loop {
            let before = set.len();
            for &f in &self.fns {
                let (tail, calls) = self.fn_targets(f);
                if tail.iter().chain(&calls).any(|t| set.contains(t)) {
                    set.insert(f);
                }
            }
            if set.len() == before {
                return set;
            }
        }
    }

    /// Finds callees that can `end`, and `cond` reads Gen3 would take from another function.
    fn analyse(&mut self) {
        self.can_end = self.closure(|f| self.region_has(f, &["end"]));
        let sets_cond = self.closure(|f| self.region_has(f, &COND_SETTERS));
        let mut foreign = BTreeSet::new();
        for (&f, blocks) in &self.regions {
            // Forward dataflow: whether `cond` was set in this function on every path.
            let mut entry: BTreeMap<u32, bool> = BTreeMap::from([(f, false)]);
            let mut work = vec![f];
            while let Some(b) = work.pop() {
                let mut set = entry[&b];
                for pc in &self.blocks[&b].insns {
                    let i = &self.insns[pc];
                    if COND_READERS.contains(&i.name) && !set {
                        foreign.insert(*pc);
                    }
                    if COND_SETTERS.contains(&i.name) {
                        set = true;
                    }
                    if matches!(i.name, "call" | "call_if")
                        && let Some(Operand::Script(t)) = i.args.last()
                        && sets_cond.contains(t)
                    {
                        set = false;
                    }
                }
                for (kind, t) in self.edges(b) {
                    if kind != Edge::Jump || !blocks.contains(&t) || t == f {
                        continue;
                    }
                    let old = entry.get(&t).copied();
                    let new = old.map_or(set, |o| o && set);
                    if old != Some(new) {
                        entry.insert(t, new);
                        work.push(t);
                    }
                }
            }
        }
        self.foreign_cond = foreign;
    }

    // ---- emission ----

    fn name_of(&self, off: u32) -> &str {
        &self.labels[self.label_at[&off]].name
    }

    fn map_of(&self, off: u32) -> &str {
        &self.labels[self.label_at[&off]].map
    }

    fn fn_path(&self, from_map: &str, f: u32) -> String {
        let (name, map) = (self.name_of(f), self.map_of(f));
        if map == from_map {
            name.to_string()
        } else {
            format!("super::{map}::{name}")
        }
    }

    fn emit_fn(&mut self, f: u32) -> Result<String> {
        let map = self.map_of(f).to_string();
        let name = self.name_of(f).to_string();
        let blocks = self.regions[&f].clone();
        let local: BTreeMap<u32, usize> = blocks.iter().enumerate().map(|(i, b)| (*b, i)).collect();
        let jumps_home = blocks.iter().any(|b| {
            self.edges(*b)
                .iter()
                .any(|&(k, t)| k == Edge::Jump && t == f)
        });
        let looped = blocks.len() > 1 || jumps_home;
        let uses_cond = self.region_has(f, &COND_READERS) || self.region_has(f, &COND_SETTERS);

        let mut s = format!("pub async fn {name}(ctx: Ctx) {{\n");
        if uses_cond {
            s.push_str("    let mut cond = Ordering::Less;\n");
        }
        let fx = FnCx {
            map: &map,
            local: &local,
            looped,
        };
        if looped {
            s.push_str("    let mut pc: u16 = 0;\n    loop {\n        match pc {\n");
            for (i, &b) in blocks.iter().enumerate() {
                writeln!(s, "            {i} => {{")?;
                writeln!(s, "                // {}", self.name_of(b))?;
                for line in self.emit_block(b, &fx)? {
                    writeln!(s, "                {line}")?;
                }
                s.push_str("            }\n");
            }
            s.push_str("            _ => unreachable!(),\n        }\n    }\n");
        } else {
            let mut lines = self.emit_block(f, &fx)?;
            if lines.last().is_some_and(|l| l == "return;") {
                lines.pop();
            }
            for line in lines {
                writeln!(s, "    {line}")?;
            }
        }
        s.push_str("}\n");
        Ok(s)
    }

    fn emit_block(&mut self, b: u32, fx: &FnCx) -> Result<Vec<String>> {
        let block = &self.blocks[&b];
        let insns: Vec<Insn> = block
            .insns
            .iter()
            .map(|pc| self.insns[pc].clone())
            .collect();
        let end = block.end;
        let mut out = Vec::new();
        let mut last_moved: Option<String> = None;
        let mut i = 0;
        while i < insns.len() {
            let insn = &insns[i];
            if self.foreign_cond.contains(&insn.off) {
                self.stats.foreign_cond += 1;
                out.push(
                    "// note: Gen3 reads the comparison result of the caller or of a callee here"
                        .to_string(),
                );
            }
            // `msgbox`: loadword 0, <text> ; callstd/gotostd MSGBOX_*.
            if insn.name == "loadword"
                && let [Operand::Byte(0), Operand::Text(Some(t))] = insn.args[..]
                && let Some(next) = insns.get(i + 1)
                && matches!(next.name, "callstd" | "gotostd")
                && let [Operand::Byte(kind)] = next.args[..]
                && let Some(k) = msgbox_kind(kind)
            {
                out.push(format!(
                    "msgbox(&ctx, {}, MsgBox::{k}).await;",
                    self.texts[&t]
                ));
                if next.name == "gotostd" {
                    out.push("return;".to_string());
                }
                i += 2;
                continue;
            }
            // `giveitem`/`finditem`: setorcopyvar VAR_0x8000, <item> ; setorcopyvar VAR_0x8001,
            // <amount> ; callstd STD_OBTAIN_ITEM/STD_FIND_ITEM.
            if insn.name == "setorcopyvar"
                && let [Operand::Half(GIVEITEM_VAR), Operand::Half(item)] = insn.args[..]
                && item < VARS_START
                && let Some(std) = insns.get(i + 2)
                && std.name == "callstd"
                && matches!(std.args[..], [Operand::Byte(0 | 1)])
                && let Some(item) = named(&names::ITEMS, item.into())
            {
                out.push(format!("ctx.set_var({}, {item}).await;", var(GIVEITEM_VAR)));
                i += 1;
                continue;
            }
            self.emit_insn(insn, fx, &mut last_moved, &mut out)?;
            i += 1;
        }
        match end {
            End::Terminated => {}
            End::Fallthrough(t) => out.extend(self.jump(t, fx)),
            End::Unknown(pc) => {
                let op = self.unknown[&pc];
                self.count_unsupported("unknown opcode");
                out.push(format!(
                    "unsupported(&ctx, \"unknown opcode {op:#04x}\").await; // at {pc:#x}"
                ));
                out.push("return;".to_string());
            }
        }
        Ok(out)
    }

    /// Lines that continue at `t`: a local block or a tail call.
    fn jump(&self, t: u32, fx: &FnCx) -> Vec<String> {
        match fx.local.get(&t) {
            Some(i) if fx.looped => {
                vec![format!("pc = {i};"), "continue;".to_string()]
            }
            _ => vec![
                format!("Box::pin({}(ctx.clone())).await;", self.fn_path(fx.map, t)),
                "return;".to_string(),
            ],
        }
    }

    fn call(&mut self, t: u32, fx: &FnCx) -> Vec<String> {
        let mut out = vec![format!(
            "Box::pin({}(ctx.clone())).await;",
            self.fn_path(fx.map, t)
        )];
        if self.can_end.contains(&t) {
            self.stats.end_in_callee += 1;
            out.push(format!(
                "// note: in Gen3, an `end` inside {} also ends this script",
                self.name_of(t)
            ));
        }
        out
    }

    fn count_unsupported(&mut self, what: &str) {
        *self.stats.unsupported.entry(what.to_string()).or_default() += 1;
    }

    fn unsupported(&mut self, insn: &Insn, out: &mut Vec<String>) {
        self.count_unsupported(insn.name);
        let args: Vec<String> = insn.args.iter().map(|a| self.arg_str(a)).collect();
        let comment = if args.is_empty() {
            String::new()
        } else {
            format!(" // {}", args.join(", "))
        };
        out.push(format!(
            "unsupported(&ctx, \"{}\").await;{comment}",
            insn.name
        ));
        if insn.is_terminator() {
            out.push("return;".to_string());
        }
    }

    fn arg_str(&self, a: &Operand) -> String {
        match *a {
            Operand::Byte(b) => b.to_string(),
            Operand::Half(h) => format!("{h:#x}"),
            Operand::Word(w) | Operand::VAddress(w) | Operand::VScript(w) | Operand::VText(w) => {
                format!("{w:#x}")
            }
            Operand::Script(s) => self.name_of(s).to_string(),
            Operand::Text(Some(t)) => self.texts[&t].clone(),
            Operand::Movement(Some(m)) => self.movements[&m].0.clone(),
            Operand::Text(None) | Operand::Movement(None) | Operand::Braille(_) => {
                "RAM".to_string()
            }
        }
    }

    fn movement_path(&self, from_map: &str, m: u32) -> String {
        let (name, map) = &self.movements[&m];
        if map == from_map {
            name.clone()
        } else {
            format!("super::{map}::{name}")
        }
    }

    fn emit_insn(
        &mut self,
        insn: &Insn,
        fx: &FnCx,
        last_moved: &mut Option<String>,
        out: &mut Vec<String>,
    ) -> Result<()> {
        use Operand::{Byte, Half, Movement, Script, Text};
        let args = &insn.args[..];
        let name = insn.name;
        match (name, args) {
            ("nop" | "nop1", _) => out.push(format!("// {name}")),
            ("end" | "return" | "returnram" | "endram", _) => out.push("return;".to_string()),
            ("call", &[Script(t)]) => out.extend(self.call(t, fx)),
            ("goto", &[Script(t)]) => out.extend(self.jump(t, fx)),
            ("goto_if" | "call_if", &[Byte(c), Script(t)]) => {
                let Some(c) = condition(c) else {
                    self.unsupported(insn, out);
                    return Ok(());
                };
                let body = if name == "goto_if" {
                    self.jump(t, fx)
                } else {
                    self.call(t, fx)
                };
                out.push(format!("if {c} {{"));
                out.extend(body.into_iter().map(|l| format!("    {l}")));
                out.push("}".to_string());
            }
            ("callstd" | "gotostd", &[Byte(n)]) => {
                out.push(self.callstd(n));
                if name == "gotostd" {
                    out.push("return;".to_string());
                }
            }
            ("callstd_if" | "gotostd_if", &[Byte(c), Byte(n)]) => {
                let Some(c) = condition(c) else {
                    self.unsupported(insn, out);
                    return Ok(());
                };
                out.push(format!("if {c} {{"));
                out.push(format!("    {}", self.callstd(n)));
                if name == "gotostd_if" {
                    out.push("    return;".to_string());
                }
                out.push("}".to_string());
            }
            ("setvar", &[Half(v), Half(x)]) if v >= VARS_START => {
                let value = match named(&names::OBJ_EVENT_GFX, x.into()) {
                    Some(g) if (VAR_OBJ_GFX_ID_0..VAR_OBJ_GFX_ID_0 + 16).contains(&v) => {
                        g.to_string()
                    }
                    _ => x.to_string(),
                };
                out.push(format!("ctx.set_var({}, {value}).await;", var(v)));
            }
            ("addvar", &[Half(v), Half(x)]) if v >= VARS_START => out.push(format!(
                "ctx.set_var({0}, ctx.var({0}).await.wrapping_add({x})).await;",
                var(v)
            )),
            ("subvar", &[Half(v), Half(x)]) if v >= VARS_START => out.push(format!(
                "ctx.set_var({0}, ctx.var({0}).await.wrapping_sub({1})).await;",
                var(v),
                vol(x)
            )),
            ("copyvar", &[Half(a), Half(b)]) if a >= VARS_START && b >= VARS_START => out.push(
                format!("ctx.set_var({}, ctx.var({}).await).await;", var(a), var(b)),
            ),
            ("setorcopyvar", &[Half(a), Half(b)]) if a >= VARS_START => {
                out.push(format!("ctx.set_var({}, {}).await;", var(a), vol(b)))
            }
            ("compare_var_to_value", &[Half(v), Half(x)]) if v >= VARS_START => {
                out.push(format!("cond = ctx.var({}).await.cmp(&{x});", var(v)))
            }
            ("compare_var_to_var", &[Half(a), Half(b)]) if a >= VARS_START && b >= VARS_START => {
                out.push(format!(
                    "cond = ctx.var({}).await.cmp(&ctx.var({}).await);",
                    var(a),
                    var(b)
                ))
            }
            ("special", &[Half(n)]) => {
                let s = self.special(n);
                out.push(format!("special(&ctx, {s}).await;"));
            }
            ("specialvar", &[Half(v), Half(n)]) if v >= VARS_START => {
                let s = self.special(n);
                out.push(format!(
                    "ctx.set_var({}, special(&ctx, {s}).await).await;",
                    var(v)
                ));
            }
            ("delay", &[Half(n)]) => out.push(format!("ctx.delay({n}).await;")),
            ("setflag" | "clearflag", &[Half(f)]) => out.push(format!(
                "ctx.set_flag({}, {}).await;",
                flag(f),
                name == "setflag"
            )),
            ("checkflag", &[Half(f)]) => out.push(format!(
                "cond = if ctx.flag({}).await {{ Ordering::Equal }} else {{ Ordering::Less }};",
                flag(f)
            )),
            (s, _) if SOUND.contains(&s) => {
                let args: Vec<String> = args.iter().map(|a| self.arg_str(a)).collect();
                out.push(format!("// {s} {}", args.join(", ")).trim_end().to_string());
            }
            (w, &[Half(m), Byte(id), Half(x), Half(y)]) if WARPS.contains(&w) => {
                let Some(map) = map_const(m) else {
                    self.unsupported(insn, out);
                    return Ok(());
                };
                let warp = if id == WARP_ID_NONE {
                    "None".to_string()
                } else {
                    format!("Some({id})")
                };
                out.push(format!(
                    "ctx.warp({map}, {warp}, {}, {}).await;{}",
                    coord(x),
                    coord(y),
                    if w == "warp" {
                        String::new()
                    } else {
                        format!(" // {w}")
                    }
                ));
            }
            ("getplayerxy", &[Half(a), Half(b)]) if a >= VARS_START && b >= VARS_START => {
                out.push("let (x, y) = ctx.player_pos().await;".to_string());
                out.push(format!("ctx.set_var({}, x as u16).await;", var(a)));
                out.push(format!("ctx.set_var({}, y as u16).await;", var(b)));
            }
            ("applymovement", &[Half(id), Movement(Some(m))]) => {
                let id = local_id(id);
                out.push(format!(
                    "ctx.move_obj({id}, &{}).await;",
                    self.movement_path(fx.map, m)
                ));
                *last_moved = Some(id);
            }
            ("applymovementat", &[Half(id), Movement(Some(m)), Half(at)])
                if self.is_current_map(at, fx) =>
            {
                let id = local_id(id);
                out.push(format!(
                    "ctx.move_obj({id}, &{}).await; // applymovementat",
                    self.movement_path(fx.map, m)
                ));
                *last_moved = Some(id);
            }
            ("waitmovement", &[Half(id)]) => out.push(self.wait_move(id, last_moved)),
            ("waitmovementat", &[Half(id), Half(at)]) if self.is_current_map(at, fx) => out.push(
                format!("{} // waitmovementat", self.wait_move(id, last_moved)),
            ),
            ("addobject" | "removeobject", &[Half(id)]) => out.push(format!(
                "ctx.{}_object({}).await; // {name}",
                if name == "addobject" { "show" } else { "hide" },
                local_id(id)
            )),
            (
                "addobjectat" | "removeobjectat" | "showobjectat" | "hideobjectat",
                &[Half(id), Half(at)],
            ) if self.is_current_map(at, fx) => out.push(format!(
                "ctx.{}_object({}).await; // {name}",
                if matches!(name, "addobjectat" | "showobjectat") {
                    "show"
                } else {
                    "hide"
                },
                local_id(id)
            )),
            ("setobjectxy", &[Half(id), Half(x), Half(y)]) => out.push(format!(
                "ctx.set_object_pos({}, {}, {}).await;",
                local_id(id),
                coord(x),
                coord(y)
            )),
            ("turnobject", &[Half(id), Byte(d)]) if dir(d).is_some() => out.push(format!(
                "ctx.turn({}, {}).await;",
                local_id(id),
                dir(d).unwrap()
            )),
            ("setobjectmovementtype", &[Half(id), Byte(t)]) if movement_type(t).is_some() => out
                .push(format!(
                    "ctx.set_movement_type({}, {}).await;",
                    local_id(id),
                    movement_type(t).unwrap()
                )),
            ("faceplayer", _) => out.push("ctx.face_player().await;".to_string()),
            ("lock", _) => out.push("ctx.lock().await;".to_string()),
            ("lockall", _) => out.push("ctx.lock_all().await;".to_string()),
            ("release", _) => out.push("ctx.release().await;".to_string()),
            ("releaseall", _) => out.push("ctx.release_all().await;".to_string()),
            ("message", &[Text(Some(t))]) => {
                out.push(format!("ctx.message({}).await;", self.texts[&t]))
            }
            ("waitmessage", _) => out.push("ctx.wait_message().await;".to_string()),
            ("closemessage", _) => out.push("ctx.close_message().await;".to_string()),
            ("waitbuttonpress", _) => out.push("ctx.wait_button().await;".to_string()),
            ("yesnobox", _) => out.push(format!(
                "ctx.set_var({}, ctx.yes_no().await as u16).await;",
                var(VAR_RESULT)
            )),
            ("random", &[Half(n)]) => out.push(format!(
                "ctx.set_var({}, ctx.random({}).await).await;",
                var(VAR_RESULT),
                vol(n)
            )),
            ("fadescreen" | "fadescreenspeed" | "fadescreenswapbuffers", &[Byte(mode), ..])
                if fade(mode).is_some() =>
            {
                out.push(format!(
                    "ctx.fade({}).await;{}",
                    fade(mode).unwrap(),
                    if name == "fadescreen" {
                        String::new()
                    } else {
                        format!(" // {name}")
                    }
                ))
            }
            ("setmetatile", &[Half(x), Half(y), Half(m), Half(imp)]) => {
                let blocked = if imp >= VARS_START {
                    format!("{} != 0", vol(imp))
                } else {
                    (imp != 0).to_string()
                };
                out.push(format!(
                    "ctx.set_metatile({}, {}, {}, {blocked}).await;",
                    coord(x),
                    coord(y),
                    vol(m)
                ))
            }
            _ => self.unsupported(insn, out),
        }
        Ok(())
    }

    fn callstd(&mut self, n: u8) -> String {
        let name = names::std_name(n);
        if name.starts_with("STD_") && names::STD_SCRIPTS.name(n.into()).is_some() {
            self.stats.stds.insert(name.clone());
            format!("callstd(&ctx, {name}).await;")
        } else {
            self.stats.stds.insert(n.to_string());
            format!("callstd(&ctx, {n}).await; // {name}")
        }
    }

    fn special(&mut self, n: u16) -> String {
        match named(&names::SPECIALS, n.into()) {
            Some(s) => {
                self.stats.specials.insert(s.to_string());
                s.to_string()
            }
            None => {
                self.stats.specials.insert(format!("{n:#x}"));
                format!("{n:#x}")
            }
        }
    }

    fn wait_move(&mut self, id: u16, last_moved: &Option<String>) -> String {
        if id != 0 {
            return format!("ctx.wait_move({}).await;", local_id(id));
        }
        match last_moved {
            Some(id) => format!("ctx.wait_move({id}).await;"),
            None => {
                self.stats.unresolved_waitmovement += 1;
                "ctx.wait_move(0).await; // 0: the object of the last applymovement".to_string()
            }
        }
    }

    /// Whether an `*at` command's map operand (group byte, num byte) is the file's map.
    fn is_current_map(&self, at: u16, fx: &FnCx) -> bool {
        names::map(at as u8, (at >> 8) as u8).is_some_and(|m| m.dir == fx.map)
    }
}

struct FnCx<'a> {
    map: &'a str,
    /// Block -> arm index (entry is 0).
    local: &'a BTreeMap<u32, usize>,
    looped: bool,
}

fn msgbox_kind(n: u8) -> Option<&'static str> {
    Some(match names::MSGBOX_TYPES.name(n.into())? {
        "MSGBOX_NPC" => "Npc",
        "MSGBOX_SIGN" => "Sign",
        "MSGBOX_DEFAULT" => "Default",
        "MSGBOX_YESNO" => "YesNo",
        "MSGBOX_AUTOCLOSE" => "Autoclose",
        "MSGBOX_GETPOINTS" => "GetPoints",
        "MSGBOX_POKENAV" => "Pokenav",
        _ => return None,
    })
}

/// `sScriptConditionTable` row as a test of `cond`.
fn condition(c: u8) -> Option<&'static str> {
    Some(match c {
        0 => "cond == Ordering::Less",
        1 => "cond == Ordering::Equal",
        2 => "cond == Ordering::Greater",
        3 => "cond != Ordering::Greater",
        4 => "cond != Ordering::Less",
        5 => "cond != Ordering::Equal",
        _ => return None,
    })
}

/// The primary name of `v` in `table`, if it is a valid Rust identifier (the prelude defines a
/// constant for each such name).
pub fn named(table: &names::Table, v: u32) -> Option<&'static str> {
    table.name(v).filter(|n| is_ident(n))
}

pub fn is_ident(s: &str) -> bool {
    s.chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn var(v: u16) -> String {
    named(&names::VARS, v.into()).map_or_else(|| format!("VarId({v:#x})"), str::to_string)
}

fn flag(f: u16) -> String {
    named(&names::FLAGS, f.into()).map_or_else(|| format!("FlagId({f:#x})"), str::to_string)
}

/// A `VarGet` operand as a `u16` expression: the var's value for ids ≥ 0x4000, else the literal.
fn vol(x: u16) -> String {
    if x >= VARS_START {
        format!("ctx.var({}).await", var(x))
    } else {
        x.to_string()
    }
}

/// A `VarGet` coordinate as an `i16` expression.
fn coord(x: u16) -> String {
    if x >= VARS_START {
        format!("ctx.var({}).await as i16", var(x))
    } else {
        (x as i16).to_string()
    }
}

/// A `VarGet` local id as a `u8` expression.
fn local_id(id: u16) -> String {
    if id >= VARS_START {
        format!("ctx.var({}).await as u8", var(id))
    } else if id == LOCALID_PLAYER {
        "PLAYER".to_string()
    } else {
        (id as u8).to_string()
    }
}

/// A map operand (group byte, then num byte) as its `MAP_*` constant.
fn map_const(m: u16) -> Option<&'static str> {
    names::map(m as u8, (m >> 8) as u8).map(|m| m.constant)
}

/// `DIR_SOUTH..DIR_EAST`.
fn dir(d: u8) -> Option<&'static str> {
    Some(match d {
        1 => "Dir::Down",
        2 => "Dir::Up",
        3 => "Dir::Left",
        4 => "Dir::Right",
        _ => return None,
    })
}

/// `FADE_FROM_BLACK`/`FADE_TO_BLACK` (white fades have no `Fade`).
fn fade(mode: u8) -> Option<&'static str> {
    Some(match mode {
        0 => "Fade::FromBlack",
        1 => "Fade::ToBlack",
        _ => return None,
    })
}

/// `MOVEMENT_TYPE_*` as an `engine::data::MovementType` expression.
fn movement_type(t: u8) -> Option<&'static str> {
    Some(match names::MOVEMENT_TYPES.name(t.into())? {
        "MOVEMENT_TYPE_LOOK_AROUND" => "MovementType::LookAround",
        "MOVEMENT_TYPE_WANDER_AROUND" => "MovementType::Wander",
        "MOVEMENT_TYPE_WANDER_UP_AND_DOWN" | "MOVEMENT_TYPE_WANDER_DOWN_AND_UP" => {
            "MovementType::WanderVertical"
        }
        "MOVEMENT_TYPE_WANDER_LEFT_AND_RIGHT" | "MOVEMENT_TYPE_WANDER_RIGHT_AND_LEFT" => {
            "MovementType::WanderHorizontal"
        }
        "MOVEMENT_TYPE_FACE_DOWN" => "MovementType::Face(Dir::Down)",
        "MOVEMENT_TYPE_FACE_UP" => "MovementType::Face(Dir::Up)",
        "MOVEMENT_TYPE_FACE_LEFT" => "MovementType::Face(Dir::Left)",
        "MOVEMENT_TYPE_FACE_RIGHT" => "MovementType::Face(Dir::Right)",
        "MOVEMENT_TYPE_WALK_IN_PLACE_DOWN" => "MovementType::WalkInPlace(Dir::Down)",
        "MOVEMENT_TYPE_WALK_IN_PLACE_UP" => "MovementType::WalkInPlace(Dir::Up)",
        "MOVEMENT_TYPE_WALK_IN_PLACE_LEFT" => "MovementType::WalkInPlace(Dir::Left)",
        "MOVEMENT_TYPE_WALK_IN_PLACE_RIGHT" => "MovementType::WalkInPlace(Dir::Right)",
        "MOVEMENT_TYPE_INVISIBLE" => "MovementType::Invisible",
        _ => return None,
    })
}
