//! Event scripts to async Rust (Milestone 3 Task B).
//!
//! Every script reachable from the exported maps' roots is decoded ([`scripts::decode`]) and
//! written as `scripts/<Map>.rs`, plus `text/<lang>.ron` and `scripts/index.ron`.
//!
//! **Names** follow [`crate::schema`]. Roots (canonical names only) are labelled first, in map
//! export order. Then each root's code is scanned in that order, linearly with a FIFO of jump
//! targets; every `goto`/`call`/script-pointer target not labelled yet becomes `<Root>_L<n>`.
//! Labels are then ordered root by root (each root, then the labels its scan created), and texts
//! and movements are named `<Label>_T<n>`/`<Label>_M<n>` after the first label in that order
//! whose straight-line block uses them. Everything named after a root lives in that root's map
//! file, in that order.
//!
//! **Functions.** A *block* runs from a label to the next label or terminator. Roots, `call`
//! targets and other script-pointer operands (`trainerbattle` continue scripts) are functions;
//! so is any block reached by `goto`/fallthrough from more than one function. A function owns
//! the blocks it reaches by `goto` and fallthrough without entering another function; with more
//! than one block (or a jump back to its entry) it is a `loop { match pc { … } }`. Entering
//! another function by `goto` or fallthrough is a tail call: `Box::pin(f(ctx.clone())).await;
//! return;`.
//!
//! **Generated file contract** (`content::prelude` implements it, see the M3 plan): no `use`
//! lines and no inner attributes, only `pub async fn <Name>(ctx: Ctx)` and `pub static`
//! movement tables. Content wraps each file as
//! `#[allow(…)] pub mod <Map> { use crate::prelude::*; include!(…); }` inside `crate::scripts`,
//! so calls into another map's file are `super::<Map>::<Name>`.
//!
//! **Gen3 semantics kept:** the comparison register is a local `cond: Ordering` (`checkflag`
//! sets `Equal` when the flag is set, `Less` otherwise, as `comparisonResult` 1/0); `yesnobox`
//! and `random` write `VAR_RESULT`; operands the game reads with `VarGet` read the var at run
//! time when they are ≥ 0x4000. What a local `cond` and plain fns cannot express (a callee's
//! `end` stopping its caller, `cond` flowing across a call) is commented in the output and
//! counted in [`Stats`].

use crate::schema::{ScriptEntry, ScriptIndex, TextFile};
