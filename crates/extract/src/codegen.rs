/// One map's roots, as [`roots::named_roots`] gives them.
#[derive(Clone, Debug)]
pub struct MapRoots {
    pub map: String,
    pub roots: Vec<(String, u32)>,
}

/// What generation produced, for reports and tests.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Stats {
    /// Generated functions (roots and label functions).
    pub fns: usize,
    /// Labels, including those that stay blocks of a function.
    pub labels: usize,
    pub texts: usize,
    pub movements: usize,
    /// `unsupported(…)` calls emitted, by command name.
    pub unsupported: BTreeMap<String, usize>,
    /// Undecodable instructions: offset -> opcode.
    pub unknown_ops: BTreeMap<u32, u8>,
    /// Movement actions with no `Step`, by `MOVEMENT_ACTION_*` name.
    pub unknown_movement_actions: BTreeMap<String, usize>,
    /// `SPECIAL_*` and `STD_*` names emitted.
    pub specials: BTreeSet<String>,
    pub stds: BTreeSet<String>,
    /// `call` sites into a function that can `end` (Gen3 would stop the whole script).
    pub end_in_callee: usize,
    /// Reads of `cond` that Gen3 would take from the caller or from a callee.
    pub foreign_cond: usize,
    /// `waitmovement 0` with no `applymovement` earlier in the same block.
    pub unresolved_waitmovement: usize,
}

#[derive(Clone, Debug, Default)]
pub struct Generated {
    /// Map name -> source of `scripts/<Map>.rs` (every map has one, maybe with no items).
    pub files: BTreeMap<String, String>,
    pub texts: TextFile,
    /// Text name -> ROM file offset.
    pub text_offsets: BTreeMap<String, u32>,
    pub index: ScriptIndex,
    pub stats: Stats,
}

/// `// @generated …` first line of every generated file.
pub fn header(game_code: &str, sha1: &str) -> String {
    format!(
        "// @generated by cargo xtask extract from {game_code} {sha1}; edit by copying into \
         content/src/scripts/\n"
    )
}

/// How a block's straight-line code ends.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum End {
    /// The last instruction is a terminator.
    Terminated,
    /// Runs into the label at this offset.
    Fallthrough(u32),
    /// Runs into an undecodable instruction at this offset.
    Unknown(u32),
}

struct Block {
    insns: Vec<u32>,
    end: End,
}

struct Label {
    off: u32,
    name: String,
    map: String,
    root: bool,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Edge {
    /// `goto`/`goto_if`/fallthrough: stays in the function or tail-calls.
    Jump,
    /// `call`/`call_if`/other script pointers: always a function.
    Call,
}

