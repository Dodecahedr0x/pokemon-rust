#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_by_value_and_prefixed() {
        for t in [&WEATHER, &MAP_TYPES, &BATTLE_SCENES, &MUSIC] {
            assert!(
                t.entries.windows(2).all(|w| w[0].0 < w[1].0),
                "{}",
                t.prefix
            );
            assert!(t.entries.iter().all(|e| e.1.starts_with(t.prefix)));
        }
        assert_eq!(MUSIC.name(405), Some("MUS_LITTLEROOT"));
        assert_eq!(MUSIC.name_or_hex(1), "MUS_0x1");
    }
}
